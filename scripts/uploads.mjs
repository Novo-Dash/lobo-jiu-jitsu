// ─────────────────────────────────────────────────────────────────────────────
// uploads.mjs: photos the client/Adryan sent after the prototype (reference/uploads), resized for
// the size they are shown at, plus a -sm for the phones. Writes src/data/images.uploads.gen.ts.
// Run: `npm run uploads` after adding or replacing a file in reference/uploads.
// ─────────────────────────────────────────────────────────────────────────────
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const src = path.join(root, 'reference', 'uploads'), out = path.join(root, 'public', 'images')

// file → name on the site, widest width shown (×2), width of the phone variant
const UPLOADS = [
  { file: 'kids-bag.webp', name: 'bag', w: 1254, sm: 760, q: 70 },     // Parents backpack, the object of the section: ≤ 660 CSS px
  { file: 'kids-bag-wide.webp', name: 'bag_wide', w: 1866, sm: 1200, q: 70 }, // Parents desktop: the bag with the white belt across, in the card
  { file: 'fred-coach.webp', name: 'fred_coach', w: 812, sm: 440 }, // Professor cut-out, ≤ 640 CSS px tall
  // Black November (12/11): the gi and the rash guard keyed out of the yellow panel of Lobo's campaign
  // art (black-november-art.webp), shown ≤ 420 CSS px wide behind the member card
  { file: 'bn-uniform.png', name: 'bn_uniform', w: 515, sm: 360, q: 86 },
]

const sizes = {}
for (const u of UPLOADS) {
  const img = sharp(path.join(src, u.file)), meta = await img.metadata()
  const w = Math.min(u.w, meta.width)
  const info = await sharp(path.join(src, u.file)).resize({ width: w }).webp({ quality: u.q ?? 80, alphaQuality: 85, effort: 6 }).toFile(path.join(out, `${u.name}.webp`))
  await sharp(path.join(src, u.file)).resize({ width: u.sm }).webp({ quality: 78, alphaQuality: 80, effort: 6 }).toFile(path.join(out, `${u.name}-sm.webp`))
  sizes[u.name] = { w: info.width, h: info.height, sm: u.sm }
  const kb = (f) => (fs.statSync(path.join(out, f)).size / 1024).toFixed(0)
  console.log(`uploads: ${u.name} ${info.width}×${info.height} ${kb(`${u.name}.webp`)} KB · sm ${kb(`${u.name}-sm.webp`)} KB`)
}
fs.writeFileSync(path.join(root, 'src', 'data', 'images.uploads.gen.ts'), `// generated by scripts/uploads.mjs\nexport const UPLOADS = ${JSON.stringify(sizes, null, 2)} as const\n`)
