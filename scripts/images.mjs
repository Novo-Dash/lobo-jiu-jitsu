// ─────────────────────────────────────────────────────────────────────────────
// images.mjs: pulls the photos already treated for the approved prototype
// (reference/prototipo-aprovado-LOBO.html, embedded as data URIs) into public/images,
// with the names of PRD §15, a small variant for the phones and the OG image.
// Run once: `npm run images`. Re-run only if the prototype file changes.
// ─────────────────────────────────────────────────────────────────────────────
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const out = path.join(root, 'public', 'images')
fs.mkdirSync(out, { recursive: true })
const html = fs.readFileSync(path.join(root, 'reference', 'prototipo-aprovado-LOBO.html'), 'utf8')

// Data URIs in document order, deduplicated (the same order the prototype uses them).
const seen = new Set(), blobs = []
for (const m of html.matchAll(/data:image\/(png|webp|jpeg);base64,([A-Za-z0-9+/=]+)/g)) {
  if (m[2].length < 400 || seen.has(m[2])) continue
  seen.add(m[2]); blobs.push({ ext: m[1], buf: Buffer.from(m[2], 'base64') })
}

// Index in the prototype → file name (PRD §15).
const NAMES = [
  'logo', 'hero', 'p_little', 'p_kids', 'p_juniors', 'p_adults', 'polaroid', 'fred_cut',
  'why_prof', 'why_family', 'why_space', 'step_who', 'gal_coach', 'step_drill', 'gal_group',
  'logo_black', 'final', 'storefront', 'gal_class', 'gal_women', 'gal_kidsgrp', 'gal_kids',
  'gal_adults', 'gal_team',
]
if (blobs.length !== NAMES.length) throw new Error(`images: expected ${NAMES.length} images, found ${blobs.length}`)

const sizes = {}
for (const [i, b] of blobs.entries()) {
  const name = NAMES[i], meta = await sharp(b.buf).metadata()
  const file = `${name}.${b.ext}`
  fs.writeFileSync(path.join(out, file), b.buf)
  sizes[name] = { w: meta.width, h: meta.height }
  // a lighter variant for the phones: half of the big photos, 400px for the card-sized ones
  if (b.ext === 'webp' && meta.width >= 480) {
    const w = name === 'hero' ? 1200 : meta.width > 900 ? Math.round(meta.width / 2) : 400
    await sharp(b.buf).resize({ width: w }).webp({ quality: 80, alphaQuality: 90 }).toFile(path.join(out, `${name}-sm.webp`))
    sizes[name].sm = w
  }
}

// OG image 1200×630: the hero class + the white logo, on the same left gradient as the hero card.
const logo = await sharp(path.join(out, 'logo.png')).resize({ height: 120 }).toBuffer()
const shade = Buffer.from(`<svg width="1200" height="630"><defs><linearGradient id="g" x1="0" x2="1"><stop offset="0" stop-color="rgb(11,11,12)" stop-opacity=".88"/><stop offset=".6" stop-color="rgb(11,11,12)" stop-opacity=".2"/><stop offset="1" stop-color="rgb(11,11,12)" stop-opacity="0"/></linearGradient></defs><rect width="1200" height="630" fill="url(#g)"/></svg>`)
await sharp(path.join(out, 'hero.webp')).resize(1200, 630, { fit: 'cover', position: 'attention' })
  .composite([{ input: shade }, { input: logo, left: 64, top: 64 }]).jpeg({ quality: 84 }).toFile(path.join(root, 'public', 'og-image.jpg'))

fs.writeFileSync(path.join(root, 'src', 'data', 'images.gen.ts'),
  `// generated by scripts/images.mjs: real pixel sizes of public/images (width/height of every <img>)\nexport const IMG = ${JSON.stringify(sizes, null, 2)} as const\n`)
console.log(`images: ${blobs.length} files · og-image.jpg`)
